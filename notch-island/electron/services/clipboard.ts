import { clipboard } from "electron";
import { randomUUID } from "node:crypto";
import { osascript } from "../exec";
import { store } from "../store";
import type { ClipItem, ClipKind } from "../../shared/types";

const MAX_ITEMS = 20;
// パスワードマネージャーが付ける「保存しないで」の印（nspasteboard.org の取り決め）
const CONCEALED = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"];
const SECRET_RE = [
  /^sk-[A-Za-z0-9_-]{20,}$/, // API キー
  /^(ghp|gho|ghs|github_pat)_[A-Za-z0-9_]{20,}$/,
  /^AKIA[0-9A-Z]{16}$/,
  /^xox[abp]-[A-Za-z0-9-]{10,}$/,
  /-----BEGIN [A-Z ]*PRIVATE KEY-----/,
];

let last = "";
let ignoreNext = "";

export function classify(text: string): ClipKind {
  const t = text.trim();
  if (/^https?:\/\/\S+$/.test(t)) return "url";
  if (/^(#[0-9a-f]{3,8}|rgba?\([^)]*\)|hsla?\([^)]*\)|oklch\([^)]*\))$/i.test(t)) return "color";
  if (/[{};=]|=>|^\s*(import|const|let|function|def|npm|git|cd)\b/m.test(t)) return "code";
  return "text";
}

function looksSecret(text: string) {
  const t = text.trim();
  if (SECRET_RE.some((r) => r.test(t))) return true;
  // 空白のない長いランダム文字列（大小英字と数字が混ざる）はトークンとみなす
  return t.length >= 32 && !/\s/.test(t) && /[a-z]/.test(t) && /[A-Z]/.test(t) && /\d/.test(t) && !/^https?:/.test(t);
}

function poll() {
  const text = clipboard.readText();
  if (!text || text === last) return;
  last = text;
  if (text === ignoreNext) return;
  if (clipboard.availableFormats().some((f) => CONCEALED.includes(f)) || looksSecret(text)) return;
  const item: ClipItem = { id: randomUUID(), text: text.slice(0, 4000), kind: classify(text), at: Date.now() };
  store.set((s) => ({ clipboard: [item, ...s.clipboard.filter((c) => c.text !== item.text)].slice(0, MAX_ITEMS) }));
  store.flash("clipboard");
}

export function startClipboard() {
  last = clipboard.readText();
  setInterval(poll, 600);
}

/** 履歴の項目をクリップボードに戻し、前面アプリに ⌘V を送る（アクセシビリティ権限が必要） */
export async function pasteClip(id: string, beforePaste: () => void) {
  const item = store.state.clipboard.find((c) => c.id === id);
  if (!item) return;
  ignoreNext = item.text;
  clipboard.writeText(item.text);
  beforePaste();
  await new Promise((r) => setTimeout(r, 120));
  await osascript('tell application "System Events" to keystroke "v" using command down').catch((e) =>
    console.error("貼り付けに失敗しました（アクセシビリティ権限を確認）:", e),
  );
}

export function removeClip(id: string) {
  store.set((s) => ({ clipboard: s.clipboard.filter((c) => c.id !== id) }));
}
